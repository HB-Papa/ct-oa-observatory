"""Step 2c: data quality report for the harvest.

Reads the tidy tables (no API calls) and writes docs/data-quality.md plus
CSVs in data/derived/quality/. Checks:
1. Completeness: harvested counts vs the phase 1 group_by counts, per institution and year.
2. Missing fields.
3. OA status mix.
4. Repository records typed as articles (the Connecticut College 2026 issue).
5. Works with no reported institution after flattening (should be zero), very
   large author lists, duplicate DOIs, APC fields.
"""
from __future__ import annotations

import duckdb
import pandas as pd

from pipeline.config import DERIVED, ROOT, snapshot
from pipeline.institutions import INSTITUTIONS, NAMES

Q = DERIVED / "quality"


def md(df: pd.DataFrame) -> str:
    return df.to_markdown(index=False) if len(df) else "_none_"


def main():
    Q.mkdir(parents=True, exist_ok=True)
    con = duckdb.connect()
    for t in ("works", "work_institutions", "work_locations"):
        con.execute(f"CREATE VIEW {t} AS SELECT * FROM read_parquet('{(DERIVED / f'{t}.parquet').as_posix()}')")
    out = ["# Data quality report (phase 2)", "",
           f"Snapshot {snapshot()['snapshot_date']}. Generated by `pipeline/s05_quality_report.py` from the tidy tables. "
           "Scope: articles and reviews, not retracted, 2015–2026, 17 institutions.", ""]

    # 1. Completeness against the phase 1 group_by counts
    cand = pd.read_parquet(DERIVED / "institution_candidates.parquet")
    expected_rows = []
    for key, name, ids, _ in INSTITUTIONS:
        r = cand[cand.openalex_id == "|".join(ids)].iloc[0]
        for y in range(2015, 2027):
            expected_rows.append({"institution_key": key, "publication_year": y,
                                  "group_by_count": int(r[f"y{y}"])})
    con.register("expected", pd.DataFrame(expected_rows))
    comp = con.execute("""
        SELECT e.institution_key, e.publication_year, e.group_by_count,
               COALESCE(h.n, 0) AS harvested, COALESCE(h.n, 0) - e.group_by_count AS diff
        FROM expected e LEFT JOIN (
            SELECT institution_key, publication_year, COUNT(*) n FROM work_institutions GROUP BY ALL) h
        USING (institution_key, publication_year)
        ORDER BY 1, 2""").df()
    comp.to_csv(Q / "completeness_by_institution_year.csv", index=False)
    summ = comp.groupby("institution_key", as_index=False)[["group_by_count", "harvested", "diff"]].sum()
    summ["name"] = summ.institution_key.map(NAMES)
    out += ["## 1. Completeness", "",
            "Harvested works per institution compared with the phase 1 `group_by` counts (same filter). "
            "Small differences are expected because OpenAlex updates continuously between the two queries.", "",
            md(summ[["name", "group_by_count", "harvested", "diff"]]), "",
            f"Institution-years with any difference: {(comp['diff'] != 0).sum()} of {len(comp)}. "
            f"Largest absolute difference: {comp['diff'].abs().max()}.", ""]

    total = con.execute("SELECT COUNT(*) FROM works").fetchone()[0]
    by_year = con.execute("SELECT publication_year, COUNT(*) works FROM works GROUP BY 1 ORDER BY 1").df()
    out += [f"Total unique works: **{total:,}**.", "", md(by_year), ""]

    # 2. Missing fields
    miss = con.execute("""
        SELECT 'doi' AS field, AVG((doi IS NULL)::INT) share_missing FROM works
        UNION ALL SELECT 'oa_status', AVG((oa_status IS NULL)::INT) FROM works
        UNION ALL SELECT 'primary_topic', AVG((topic_id IS NULL)::INT) FROM works
        UNION ALL SELECT 'source (journal or repository)', AVG((source_id IS NULL)::INT) FROM works
        UNION ALL SELECT 'publisher', AVG((publisher_name IS NULL)::INT) FROM works
        UNION ALL SELECT 'language', AVG((language IS NULL)::INT) FROM works
        UNION ALL SELECT 'corresponding_institution_ids (empty)', AVG((n_corresponding_institutions = 0)::INT) FROM works
        UNION ALL SELECT 'apc_list (all works)', AVG((apc_list_usd IS NULL)::INT) FROM works
        UNION ALL SELECT 'apc_list (gold + hybrid works)', AVG((apc_list_usd IS NULL)::INT) FROM works WHERE oa_status IN ('gold','hybrid')
        UNION ALL SELECT 'apc_paid (all works)', AVG((apc_paid_usd IS NULL)::INT) FROM works
    """).df()
    miss["share_missing"] = (miss.share_missing * 100).round(1).astype(str) + "%"
    miss.to_csv(Q / "missing_fields.csv", index=False)
    by_year_corr = con.execute("""SELECT publication_year,
        ROUND(100 * AVG((n_corresponding_institutions > 0)::INT), 1) AS pct_with_corresponding_institution
        FROM works GROUP BY 1 ORDER BY 1""").df()
    out += ["## 2. Missing fields", "", md(miss), "",
            "Corresponding-institution coverage by year (needed for the defensible APC estimate):", "",
            md(by_year_corr), ""]

    # 3. OA status mix
    oa = con.execute("""SELECT oa_status, COUNT(*) works,
                               ROUND(100.0 * COUNT(*) / SUM(COUNT(*)) OVER (), 1) pct
                        FROM works WHERE publication_year <= 2025 GROUP BY 1 ORDER BY 2 DESC, 1""").df()
    cat = con.execute("""SELECT oa_category, COUNT(*) works, ROUND(100.0 * COUNT(*) / SUM(COUNT(*)) OVER (), 1) pct
                         FROM works WHERE publication_year <= 2025 AND in_scope GROUP BY 1 ORDER BY 2 DESC, 1""").df()
    out += ["## 3. OA status mix, statewide 2015–2025", "",
            "OpenAlex `oa_status`, all harvested works (before exclusions):", "", md(oa), "",
            "Reported `oa_category` (diamond split by confirmed $0 fee), in-scope works:", "", md(cat), ""]

    # 4. Repository records
    repo = con.execute("""
        SELECT wi.institution_key, w.publication_year, COUNT(*) works,
               SUM((w.doi IS NULL)::INT) AS without_doi
        FROM works w JOIN work_institutions wi USING (work_id)
        WHERE w.primary_is_repository GROUP BY ALL ORDER BY works DESC, institution_key, publication_year""").df()
    repo.to_csv(Q / "repository_primary_records.csv", index=False)
    repo_total = con.execute(
        "SELECT COUNT(*), SUM((doi IS NULL)::INT) FROM works WHERE primary_is_repository").fetchone()
    top_repo_sources = con.execute("""SELECT source_name, COUNT(*) works, SUM((doi IS NULL)::INT) without_doi
        FROM works WHERE primary_is_repository GROUP BY 1 ORDER BY 2 DESC, 1 LIMIT 15""").df()
    repo_by_inst = (repo.groupby("institution_key", as_index=False)[["works", "without_doi"]].sum()
                    .sort_values("works", ascending=False))
    repo_by_year = repo.groupby("publication_year", as_index=False)[["works"]].sum()
    out += ["## 4. Repository records typed as articles", "",
            f"Works whose primary location is a repository rather than a journal: **{repo_total[0]:,}** "
            f"({100 * repo_total[0] / total:.1f}% of all works), of which {repo_total[1]:,} have no DOI.", "",
            "By institution (all years):", "", md(repo_by_inst), "",
            "By year (institution-work rows):", "", md(repo_by_year), "",
            "Top repository sources:", "", md(top_repo_sources), ""]

    # 5. Other checks
    orphans = con.execute("SELECT COUNT(*) FROM works WHERE n_reported_institutions = 0").fetchone()[0]
    big = con.execute("SELECT COUNT(*) FROM works WHERE n_authorships > 100").fetchone()[0]
    dup = con.execute("""SELECT COUNT(*) FROM (SELECT doi FROM works WHERE doi IS NOT NULL
                         GROUP BY 1 HAVING COUNT(*) > 1)""").fetchone()[0]
    paid = con.execute("""SELECT COUNT(*) FILTER (WHERE apc_paid_usd IS NOT NULL),
        COUNT(*) FILTER (WHERE apc_paid_usd IS NOT NULL AND apc_paid_usd = apc_list_usd) FROM works""").fetchone()
    multi = con.execute("SELECT COUNT(*) FROM works WHERE n_reported_institutions > 1").fetchone()[0]
    out += ["## 5. Other checks", "",
            f"- Works with no reported institution after flattening: **{orphans}** (should be 0).",
            f"- Works shared by two or more of the 17 institutions: {multi:,} ({100 * multi / total:.1f}%). "
            "These are counted once statewide.",
            f"- Works with more than 100 authors: {big:,}. OpenAlex list results cap authorships at 100, "
            "so these were re-fetched one by one with full author lists (s03b, 0 credits). "
            "See docs/verification.md.",
            f"- DOIs appearing on more than one work ID: {dup:,}.",
            f"- `apc_paid` filled: {paid[0]:,} works, equal to `apc_list` in {paid[1]:,}. "
            "OpenAlex gives no provenance for `apc_paid`, so it is not treated as an actual payment.", ""]
    # 6. Exclusions applied (rule A, meeting abstracts, affiliation corrections)
    excl = con.execute("""SELECT wi.institution_key, COUNT(*) excluded
        FROM works w JOIN work_institutions wi USING (work_id) WHERE NOT wi.in_scope
        GROUP BY 1 ORDER BY 2 DESC, 1""").df()
    n_excl, n_in = con.execute("SELECT COUNT(*) FILTER (WHERE NOT in_scope), COUNT(*) FILTER (WHERE in_scope) FROM works").fetchone()
    con.execute(f"""COPY (SELECT work_id, publication_year, source_name, title, exclude_reason FROM works WHERE NOT in_scope
                 ORDER BY publication_year, source_name, work_id) TO '{(Q / "excluded_works.csv").as_posix()}' (HEADER)""")
    con.execute(f"""COPY (SELECT exclude_reason,
                 CASE WHEN publication_year <= 2025 THEN 'complete' ELSE 'incomplete' END AS period, COUNT(*) works
                 FROM works WHERE NOT in_scope GROUP BY ALL ORDER BY 1, 2)
                 TO '{(Q / "exclusions_summary.csv").as_posix()}' (HEADER)""")
    out += ["## 6. Exclusions applied", "",
            "Rule A (approved 2026-11-16): works whose primary location is a repository and that have no DOI "
            "are excluded from every metric. They stay in the tables with `in_scope = false`.", "",
            "Meeting abstracts (approved 2026-11-16): conference abstracts printed in journal supplements "
            "(Neurology, The FASEB Journal, Journal of Clinical Oncology, AHA journals, Blood and a few others), "
            "matched by DOI pattern (`MEETING_ABSTRACT_DOI_PATTERNS` in s04), are excluded. OpenAlex types them "
            "as articles. Abstracts without a recognisable DOI pattern are not caught.", "",
            "Affiliation corrections (see `AFFILIATION_CORRECTIONS` in s04): institution credits OpenAlex "
            "assigned in error are flagged `affiliation_corrected` and left out of metrics. A work whose only "
            "Connecticut credit was corrected is excluded.", "",
            md(con.execute("""SELECT institution_key, COUNT(*) corrected_credits FROM work_institutions
                              WHERE affiliation_corrected GROUP BY 1 ORDER BY 1""").df()), "",
            md(con.execute("SELECT exclude_reason, COUNT(*) works FROM works WHERE NOT in_scope GROUP BY 1 ORDER BY 1").df()), "",
            f"Excluded: **{n_excl:,}** works. Counted in metrics: **{n_in:,}** works. "
            "The list is in `data/derived/quality/excluded_works.csv`.", "", md(excl), ""]
    (ROOT / "docs" / "data-quality.md").write_text("\n".join(out), encoding="utf-8")
    print("\n".join(out))


if __name__ == "__main__":
    main()
